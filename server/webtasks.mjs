import { createHash, randomBytes } from 'node:crypto'
import dns from 'node:dns/promises'
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { ROOT } from './paths.mjs'
import { FetchError, isPublicIp, validateUrl } from './safefetch.mjs'

// "URL -> live web task": a copy of MatrAIx's reference Playwright web task (its verifier and report files are copied
// byte for byte) with a new brief. The reference task must have been validated on this server first (see validation.mjs).
const MATRAIX_DIR = join(ROOT, 'vendor', 'MatrAIx')
const DATA_DIR = join(ROOT, 'data')
const WEB_FILE = join(DATA_DIR, 'web-tasks.json')
export const WEB_TASKS_DIR = join(DATA_DIR, 'web-tasks')
export const WEB_ID_RE = /^wt_[a-f0-9]{10}$/
export const REFERENCE_TASK = 'example-web-playwright_quote-choice'
export const MAX_WEB_PERSONAS = 5
const MAX_WEB_TASKS = 50
const COPIED = ['tests/test.sh', 'tests/test_state.py', 'tests/verifier_env.sh', 'input/self_report_schema.yaml', 'persona_strategy.json', 'reporting.json']

const CONTROL = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g
const norm = (s) => String(s ?? '').replace(CONTROL, '').replace(/[ \t]+/g, ' ').trim()
const sha = (buf) => createHash('sha256').update(buf).digest('hex')

export const referenceDir = (root = MATRAIX_DIR) => join(root, 'application', 'tasks', REFERENCE_TASK)

function readList() {
  try {
    return JSON.parse(readFileSync(WEB_FILE, 'utf8'))
  } catch {
    return []
  }
}
export const getWebTask = (id) => (WEB_ID_RE.test(id) ? readList().find((x) => x.id === id) : undefined)
export const listWebTasks = () => readList()

/** Resolves the host and requires every address to be public (the agent's browser runs on this server). */
export async function assertPublicHost(u, lookup = dns.lookup) {
  const host = u.hostname.replace(/^\[|\]$/g, '')
  let addrs
  try {
    addrs = await lookup(host, { all: true })
  } catch {
    throw new FetchError('unresolvable_host')
  }
  if (!addrs.length || !addrs.every((a) => isPublicIp(a.address))) throw new FetchError('blocked_host')
}

export function validateWebInput(body) {
  const title = norm(body?.title)
  const goal = norm(body?.goal)
  if (body?.confirmPermission !== true) throw new FetchError('permission_required')
  if (title.length < 3 || title.length > 80) throw new FetchError('invalid_title')
  if (goal.length < 10 || goal.length > 600) throw new FetchError('invalid_goal')
  const u = validateUrl(body?.url) // http(s), no credentials, default ports, no private hosts
  return { title, goal, u }
}

/** Generated files (everything except the byte-copied verifier files). */
export function webTaskFiles({ id, title, url, goal }, referenceToml) {
  const name = `application/teknodoz-web-${id}`
  let toml = referenceToml.replace(/^name = ".*"$/m, `name = "${name}"`).replace(/^tags = .*$/m, 'tags = [ "teknodoz", "custom web study", "playwright dom browsing",]')
  if (!toml.includes(name) || !toml.includes('custom web study')) throw new Error('reference_format_changed')
  const instruction = `# Choose one item

Read the scenario brief in \`input/context.md\`, browse the site as yourself, then pick the one item (a product, offer, article, page or quote) you would most want to choose, save or come back to.

Save your choice to \`/app/output/quote_choice.json\`:

\`\`\`json
{
  "decision_subject_id": "<stable slug or site id for the chosen item>",
  "decision_subject_label": "<item name or text exactly as shown>",
  "decision_outcome": "selected",
  "basis_primary": "<price|quality|features|convenience|taste|trust|familiarity|novelty|fit|other>",
  "exploration_style": "<quick_pick|compared_multiple|deep_research|hesitant>",
  "reason": "<why this item matched you>",
  "task_author": "<brand, seller, author or publisher exactly as shown>"
}
\`\`\`

Requirements:

- \`decision_subject_id\` can be a simple slug derived from the item if the page does not expose a cleaner id.
- \`basis_primary\` should capture the main reason you chose it.
- Keep \`reason\` specific to the chosen item and what mattered to you.

No login, purchase or sharing action is required.
`
  const context = `# Task context

Study: ${title}

Browse the public website ${url} as yourself. Explore at least a few pages or items, then pick the **one item** you would most want to choose.

What the study owner wants to learn: ${goal}

Stay on this site and the pages it links to. Do not log in, buy anything or submit personal data. Read names and text from the live page; do not invent values.
`
  const readme = `# ${title}\n\nGenerated by Teknodoz Simulation from MatrAIx's \`${REFERENCE_TASK}\` (MIT). URL: ${url}\n\nThe verifier and report files are unchanged copies of the reference task.\n`
  return { 'task.toml': toml, 'instruction.md': instruction, 'input/context.md': context, 'README.md': readme }
}

export function writeWebTask(dir, generated, refDir) {
  for (const rel of COPIED) if (!existsSync(join(refDir, rel))) throw new Error('reference_missing')
  rmSync(dir, { recursive: true, force: true })
  for (const rel of COPIED) {
    mkdirSync(dirname(join(dir, rel)), { recursive: true })
    cpSync(join(refDir, rel), join(dir, rel))
  }
  for (const [rel, text] of Object.entries(generated)) {
    mkdirSync(dirname(join(dir, rel)), { recursive: true })
    writeFileSync(join(dir, rel), text)
  }
}

/** Static validation of a generated task: required files, verifier unchanged, brief consistent. */
export function validateWebTaskDir(dir, refDir, { id, url }) {
  const checks = []
  const add = (key, ok, detail = '') => checks.push({ key, ok, detail })
  for (const rel of ['task.toml', 'instruction.md', 'input/context.md', ...COPIED]) add(`file:${rel}`, existsSync(join(dir, rel)))
  for (const rel of COPIED) {
    const a = join(dir, rel)
    const b = join(refDir, rel)
    add(`verbatim:${rel}`, existsSync(a) && existsSync(b) && sha(readFileSync(a)) === sha(readFileSync(b)))
  }
  const read = (rel) => (existsSync(join(dir, rel)) ? readFileSync(join(dir, rel), 'utf8') : '')
  add('toml_name', read('task.toml').includes(`name = "application/teknodoz-web-${id}"`))
  add('toml_web_env', /definition = "application\/shared-web-playwright"/.test(read('task.toml')))
  add('instruction_output', read('instruction.md').includes('/app/output/quote_choice.json'))
  add('context_url', read('input/context.md').includes(url))
  add('no_solution', !existsSync(join(dir, 'solution')))
  return { ok: checks.every((c) => c.ok), checks }
}

export async function createWebTask(body, { refDir = referenceDir(), lookup } = {}) {
  const { title, goal, u } = validateWebInput(body)
  await assertPublicHost(u, lookup)
  if (!existsSync(refDir)) throw new Error('reference_missing')
  const id = `wt_${randomBytes(5).toString('hex')}`
  const url = u.href
  const files = webTaskFiles({ id, title, url, goal }, readFileSync(join(refDir, 'task.toml'), 'utf8'))
  const dir = join(WEB_TASKS_DIR, id)
  writeWebTask(dir, files, refDir)
  const check = validateWebTaskDir(dir, refDir, { id, url })
  if (!check.ok) {
    rmSync(dir, { recursive: true, force: true })
    return { error: 'validation_failed', checks: check.checks }
  }
  const entry = { id, title, url, goal, createdAt: Date.now() }
  mkdirSync(DATA_DIR, { recursive: true })
  const all = [entry, ...readList()].slice(0, MAX_WEB_TASKS)
  writeFileSync(WEB_FILE, JSON.stringify(all))
  return { task: entry, checks: check.checks }
}

export function syncWebTask(taskId, destTasksDir) {
  if (!WEB_ID_RE.test(taskId) || !existsSync(join(WEB_TASKS_DIR, taskId)) || !existsSync(destTasksDir)) return false
  cpSync(join(WEB_TASKS_DIR, taskId), join(destTasksDir, taskId), { recursive: true, force: true })
  return true
}
